package com.shop.entity;

public class 영속성_전이 {
/*
    1. 영속성 전이 (CASCADE)?
    - 엔티티의 상태를 변경할 때 마다
    엔티티와 연관된 엔티티의 상태 변화를 전파시키는 옵션
    이때 부모는 One에 해당하고
    자식은 Many에 해당합니다.

    예를 들어 Order 엔티티가 삭제되었을때
    해당 Order 엔티티와 연관 되어 있는 OrderItem엔티티가
    함께 삭제되거나,

    예를 들어 Order 엔티티를 DB에 저장할 때
    Order 엔티티에 포함된 OrderItem 엔티티도 한꺼번에 DB에 저장할수 있습니다.

    1.1. "영속화"란?
                - Spring Data JPA에서 save()를 호출하면 영속화됩니다.
                - 즉, 엔티티가 영속성 컨텍스트(1차 캐시)에 저장되고, 나중에 DB에도 반영됩니다.


    1.2. 참고
                비영속은 ‘아직 JPA가 모르는 새로운 객체’

                영속은 ‘JPA가 관리하며 DB와 연결된 상태’

                준영속은 ‘JPA가 관리하다가 관리 안하는 상태’

                삭제는 ‘JPA가 삭제 예정으로 표시한 상태’

    2. 영속성 전이 (CASCADE) 옵션 종류 표

        영속성 전이 (CASCADE) 옵션 종류                  설명
        PERSIST                           부모 엔티티가 저장(영속화)될 때 자식 엔티티도 자동으로 저장(영속화)
        MERGE                             부모 엔티티를 merge(병합)할 때, 연관된 자식 엔티티도 자동으로 merge 되는 설정입니다.
        REMOVE                            부모 엔티티가 삭제될 때 연관된 자식 엔티티로 자동으로 삭제
        REFRESH                           부모 엔티티가 refresh되면 연관된 자식 엔티티도 refresh
        DETACH                            부모 엔티티가 detach 되면 연관된 자식 엔티티도 detach 상태로 변경
        ALL                               부모 엔티티의 영속성 상태 변화를 자식 엔티티에 모두 전이

       참고.  영속성 전이 옵션을 무분별하게 사용할 경우 삭제되지 말아야 할 데이터가 삭제될 수 있으므로 조심해서 사용해야 합니다.
             영속성 전이 옵션은 단일 엔티티에 완전히 종속적이고  부모 엔티티와 자식 엔티티의 라이프사이클이 유사할 때 cascade 옵션을 활용하시기를 추천드립니다.


        ---

        ### 🎯 전제 상황:

        부모는 “부모 엔티티”, 자식은 “자식 엔티티” 라고 생각하면 됩니다.
        부모가 어떤 행동을 하면, 자식도 따라하게 만드는 기능이 바로 `Cascade`예요.
        (예: 부모가 집에 가면 자식도 따라가는 느낌!)

        ---

        | **옵션 이름**   | **쉽고 일상적인 표현**              | **어떤 상황인지 예시로 쉽게 설명**                                                      |
        | ----------- | --------------------------- | -------------------------------------------------------------------------- |
        | **PERSIST** | 부모가 저장되면 자식도 같이 저장됨         | 부모가 DB에 저장될 때, 자식도 자동으로 같이 저장돼요. 👉 예: 부모 정보 저장할 때, 자식 정보도 자동 저장됨      |
        | **MERGE**   | 부모가 수정되면 자식도 같이 수정됨         | 부모를 수정하고 DB에 반영하면, 자식도 자동으로 반영돼요. 👉 예: 부모 정보 업데이트 → 자식 정보도 같이 업데이트    |
        | **REMOVE**  | 부모가 삭제되면 자식도 같이 삭제됨         | 부모 데이터를 삭제하면, 자식도 자동으로 같이 삭제돼요. 👉 예: 게시글(부모) 삭제 시 댓글(자식)도 같이 삭제됨      |
        | **REFRESH** | 부모 정보를 새로 고치면 자식도 같이 새로 고쳐짐 | 부모 데이터를 DB에서 다시 불러오면, 자식도 새로 불러와요. 👉 예: 부모 최신 정보로 갱신 → 자식도 최신 정보로 갱신됨 |
        | **DETACH**  | 부모가 영속성에서 분리되면 자식도 같이 분리됨   | 부모가 JPA 관리에서 빠져나가면, 자식도 같이 빠져나가요. <👉 예: 부모가 JPA와 연 끊음 → 자식도 끊김         |
        | **ALL**     | 위에 있는 모든 걸 다 적용함            | 부모가 저장, 수정, 삭제, 새로고침, 분리 중 뭐든 할 때 자식도 항상 같이 행동해요. 👉 한꺼번에 다 적용되는 설정    |

        ---

        ### 📝 핵심 요약

        > `Cascade`는 부모가 행동할 때, 자식도 자동으로 따라오게 만드는 설정이에요.
        > 번거롭게 자식도 따로 처리하지 않아도 돼서, 편리하지만 조심해서 사용해야 해요.



*/
}
