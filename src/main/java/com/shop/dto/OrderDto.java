package com.shop.dto;

import lombok.Getter;
import lombok.Setter;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;


/*
 * ============================================================
 * 🛒 OrderDto - 주문서
 * ============================================================
 *
 * [비유] 식당에서 주문할 때 적는 "주문서"를 떠올려 보세요.
 *        주문서에는 "어떤 메뉴(상품)를 몇 개 주문할지"만 간단히 적습니다.
 *        이 클래스가 바로 그 "주문서" 역할을 합니다.
 *
 * [역할] 상품 상세 페이지에서 고객이 "주문하기" 버튼을 누르면,
 *        어떤 상품(itemId)을 몇 개(count) 주문하는지 정보를 담아서
 *        화면(View) -> 컨트롤러 -> 서비스로 전달하는 DTO 클래스입니다.
 *
 * [사용 흐름]
 *   1. 고객이 상품 상세 페이지에서 수량을 입력하고 "주문하기" 클릭
 *   2. 화면에서 itemId와 count가 이 DTO에 담겨 서버로 전송됨
 *   3. 서버에서 유효성 검증(@NotNull, @Min, @Max) 후 주문 처리
 *
 * [주문 수량 제한] 최소 1개 ~ 최대 999개
 * ============================================================
 */
@Getter @Setter
public class OrderDto {

    /*
     * 주문할 상품의 고유 ID
     *
     * [비유] 주문서에 적는 "메뉴 번호". 어떤 상품을 주문하는지 식별합니다.
     *        예: 상품 ID가 42번이면 42번 상품을 주문하겠다는 뜻.
     *
     * @NotNull 검증:
     *   [비유] "메뉴 번호를 안 적으면 주문 접수 불가!" 와 같습니다.
     *   null 값이 들어오면 "상품 아이디는 필수 입력 값입니다." 에러 메시지를 반환합니다.
     */
    @NotNull(message = "상품 아이디는 필수 입력 값입니다.")
    private Long itemId;

    /*
     * 주문 수량
     *
     * [비유] 주문서에 적는 "수량" 칸. "이 메뉴 몇 인분 주세요"와 같습니다.
     *        예: 2개 주문 -> count = 2
     *
     * @Min(1) 검증:
     *   [비유] "최소 1개는 주문해야 합니다!" - 0개 이하 주문은 말이 안 되죠.
     *   1보다 작은 값이 들어오면 "최소 주문 수량은 1개 입니다." 에러 메시지를 반환합니다.
     *
     * @Max(999) 검증:
     *   [비유] "한 번에 999개까지만 주문 가능합니다!" - 재고 관리와 비정상 주문 방지를 위한 제한.
     *   999보다 큰 값이 들어오면 "최대 주문 수량은 999개 입니다." 에러 메시지를 반환합니다.
     */
    @Min(value = 1, message = "최소 주문 수량은 1개 입니다.")
    @Max(value = 999, message = "최대 주문 수량은 999개 입니다.")
    private int count;

}