package com.shop.constant;

/*
    =====================================================================
    Role - 회원의 역할(권한)을 정의하는 열거형(enum) 클래스
    =====================================================================

    비유: 놀이공원의 "입장 팔찌" 색상과 같습니다.
    - 파란 팔찌(USER) : 일반 놀이기구만 탈 수 있음 → 일반 회원은 상품 조회/주문만 가능
    - 빨간 팔찌(ADMIN) : 모든 놀이기구 + 직원 전용 구역 출입 가능 → 관리자는 상품 등록/수정/삭제도 가능

    enum(열거형)을 사용하는 이유:
    - 역할이 USER, ADMIN 딱 2개로 정해져 있으므로, 실수로 "USESR" 같은 오타를 쓸 수 없습니다.
    - 컴파일(코드 변환) 시점에 잘못된 값을 걸러낼 수 있어 안전합니다.
 */
public enum Role {

    // USER : 일반 회원 - 상품 조회, 주문, 장바구니 등 기본 기능 사용 가능
    USER,

    // ADMIN : 관리자 - 일반 회원 기능 + 상품 등록/수정/삭제, 회원 관리 등 관리 기능 사용 가능
    ADMIN
}