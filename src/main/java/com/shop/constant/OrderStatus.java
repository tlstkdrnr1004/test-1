package com.shop.constant;

/*
    =====================================================================
    OrderStatus - 주문 상태를 정의하는 열거형(enum) 클래스
    =====================================================================

    비유: 배달 앱에서 주문 현황을 보여주는 "상태 표시등"과 같습니다.
    - 초록불(ORDER)  : "주문 완료! 배송 준비 중입니다"
    - 빨간불(CANCEL) : "주문이 취소되었습니다"

    주문(Order) 엔티티에서 현재 주문이 어떤 상태인지를 나타내기 위해 사용됩니다.
    enum을 사용하면 ORDER, CANCEL 외에 다른 잘못된 값이 들어올 수 없어 안전합니다.
 */
public enum OrderStatus {

    // ORDER : 주문이 정상적으로 완료된 상태 (결제 완료, 배송 준비 중)
    ORDER,

    // CANCEL : 주문이 취소된 상태 (환불 처리됨, 재고 복구됨)
    CANCEL
}
